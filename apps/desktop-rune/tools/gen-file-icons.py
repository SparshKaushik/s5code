"""File icons for the diff file tree, as web's T3_PIERRE_ICONS resolves them: @pierre/trees'
"complete" built-in set (glyphs, file-name and extension tokens, token colours) under
apps/web/src/pierre-icons.ts's own sprites and overrides.

Shapes go through gen-editor-icons.py's flattening, one single-colour layer per colour. A glyph
Pierre gives a token takes that token's colour; one T3 names directly (npm for package.json,
TypeScript for tsconfig.json) has no token and stays the muted icon colour, as on web.

    python3 -I tools/gen-file-icons.py > src/panel/diff/file_icons.rs
"""

import importlib.util
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
spec = importlib.util.spec_from_file_location("editor_icons", HERE / "gen-editor-icons.py")
ed = importlib.util.module_from_spec(spec)
spec.loader.exec_module(ed)

TREES = next((REPO / "node_modules/.pnpm").glob("@pierre+trees@*")) / "node_modules/@pierre/trees/dist"
WEB_ICONS = (REPO / "apps/web/src/pierre-icons.ts").read_text()
VIDEO = (REPO / "packages/shared/src/video.ts").read_text()

# `--trees-fg-muted`: the colour of an icon without a token.
MUTED = ("#84848a", "#84848a")
# A gradient stop in currentColor, so it survives gradient_mid and maps back to the tint.
CURRENT = "#010101"

_resolve = ed.resolve


def resolve(paint, grads):
    if paint and paint.startswith("ld:"):
        return tuple(paint[3:].split(":")), 1.0
    return _resolve(paint, grads)


ed.resolve = resolve


def js_object(source: str, name: str) -> dict:
    block = re.search(rf"const {name} = \{{(.*?)\n\}};", source, re.S).group(1)
    return {(a or b): v for a, b, v in re.findall(r'(?:"([^"]+)"|([\w]+)):\s*"([^"]+)"', block)}


def ts_object(source: str, name: str) -> str:
    return re.search(rf"\n  {name}: \{{(.*?)\n  \}},", source, re.S).group(1)


def light_dark(value: str) -> str:
    """`light-dark(a, b)`, possibly inside a var() fallback, as an `ld:a:b` paint."""
    m = re.search(r"light-dark\((#\w+),\s*(#\w+)\)", value)
    return f"ld:{m.group(1)}:{m.group(2)}" if m else value


def symbols(sprite: str) -> dict:
    out = {}
    for m in re.finditer(r'<symbol id="([\w-]+)" viewBox="([^"]+)">(.*?)</symbol>', sprite, re.S):
        body = m.group(3).replace('stop-color="currentColor"', f'stop-color="{CURRENT}"')
        body = re.sub(r'style="(fill|stroke):\s*([^"]*)"', lambda s: f'{s.group(1)}="{light_dark(s.group(2))}"', body)
        out[m.group(1)] = ET.fromstring(f'<svg viewBox="{m.group(2)}" fill="currentColor">{body}</svg>')
    return out


def tints() -> dict:
    style = (TREES / "style.js").read_text()
    palette = {k: (a, b) for k, a, b in re.findall(r"--trees-icon-(\w+): light-dark\((#\w+), (#\w+)\)", style)}
    return {tok: palette[c] for tok, c in re.findall(r"--trees-file-icon-color-([\w-]+): var\([^,]+, var\(--trees-icon-(\w+)\)\)", style)}


def main():
    built_in_js = (TREES / "builtInIcons.js").read_text()
    glyphs = symbols(built_in_js)
    t3_sprite = re.search(r"const T3_FILE_ICON_SPRITE = `(.*?)`;", WEB_ICONS, re.S).group(1)
    doc_colours = dict(re.findall(r'"(t3-file-icon-\w+)": "([^"]+)"', WEB_ICONS.split("const T3_FILE_ICON_SPRITE")[0]))
    t3_sprite = re.sub(r'\$\{DOCUMENT_ICON_COLORS\["([\w-]+)"\]\}', lambda m: doc_colours[m.group(1)], t3_sprite)
    glyphs.update(symbols(t3_sprite))
    colour = tints()

    names = js_object(built_in_js, "BUILT_IN_FILE_NAME_TOKENS")
    exts = js_object(built_in_js, "BUILT_IN_FILE_EXTENSION_TOKENS")
    overrides = js_object(built_in_js, "COMPLETE_EXTENSION_OVERRIDES")
    t3_names = dict(re.findall(r'"([^"]+)":\s*"([\w-]+)"', ts_object(WEB_ICONS, "byFileName")))
    t3_exts = {(a or b): v for a, b, v in re.findall(r'(?:"([^"]+)"|(\w+)):\s*"([\w-]+)"', ts_object(WEB_ICONS, "byFileExtension"))}
    for ext in re.findall(r'\["(\w+)", "video/', VIDEO):
        t3_exts[ext] = "t3-file-icon-video"

    print("//! Diff file tree icons, as web's T3_PIERRE_ICONS resolves them: @pierre/trees (MIT)")
    print("//! built-ins and T3's sprites. Generated by tools/gen-file-icons.py. Do not edit.")
    print("use rune::Icon;\n")
    print("type Layer = (&'static Icon, &'static str, &'static str);\n")
    emitted, sets = {}, {}

    def glyph_layers(glyph: str):
        if glyph not in emitted:
            view, parts = ed.layers(glyphs[glyph], glyph)
            merged = []
            for body, c in parts:
                c = ed.INK if c == CURRENT else c
                if merged and merged[-1][1] == c:
                    merged[-1] = (merged[-1][0] + body, c)
                else:
                    merged.append((body, c))
            const = glyph.upper().replace("-", "_")
            out = []
            for i, (body, c) in enumerate(merged):
                body = body.replace("\\", "\\\\").replace('"', '\\"')
                v = ed.fmt(view)
                print(f'static {const}_{i}: Icon = Icon {{ name: "{glyph}-{i}", view: {v if "." in v else v + ".0"}, body: "{body}" }};')
                out.append((f"{const}_{i}", c))
            emitted[glyph] = out
        return emitted[glyph]

    def set_for(glyph: str, tint) -> str:
        key = (glyph, tint)
        if key not in sets:
            rows = []
            for const, c in glyph_layers(glyph):
                light, dark = tint if c == ed.INK else c if isinstance(c, tuple) else (c, c)
                rows.append(f'(&{const}, "{light}", "{dark}")')
            sets[key] = (f"SET_{len(sets)}", rows)
        return sets[key][0]

    def named(glyph: str) -> str:
        return set_for(glyph, MUTED)

    def token(tok: str) -> str:
        return set_for(f"file-tree-builtin-{tok}", colour.get(tok, MUTED))

    arms_name = sorted((k.lower(), named(v)) for k, v in t3_names.items())
    arms_t3_ext = sorted((k.lower(), named(v)) for k, v in t3_exts.items())
    arms_builtin_name = sorted((k, token(v)) for k, v in names.items())
    arms_override = sorted((k, token(v)) for k, v in overrides.items())
    arms_ext = sorted((k, token(v)) for k, v in exts.items())
    default = token("default")

    print()
    for const, rows in sets.values():
        print(f"static {const}: [Layer; {len(rows)}] = [{', '.join(rows)}];")

    def lookup(fn: str, arms):
        print(f"fn {fn}(key: &str) -> Option<&'static [Layer]> {{")
        print("    Some(match key {")
        for k, v in arms:
            print(f'        "{k}" => &{v},')
        print("        _ => return None,")
        print("    })")
        print("}\n")

    print()
    lookup("t3_name", arms_name)
    lookup("t3_extension", arms_t3_ext)
    lookup("built_in_name", arms_builtin_name)
    lookup("complete_override", arms_override)
    lookup("built_in_extension", arms_ext)
    print("/// `path`'s icon layers, bottom first: glyph, light-theme colour, dark-theme colour. Pierre's")
    print("/// order: T3's file names, T3's extensions, then built-in names, then built-in extensions,")
    print("/// each extension tried longest first (`d.ts` before `ts`).")
    print("pub fn for_path(path: &str) -> &'static [Layer] {")
    print("    let name = path.rsplit('/').next().unwrap_or(path).to_lowercase();")
    print("    let candidates: Vec<&str> = name.match_indices('.').map(|(i, _)| &name[i + 1..]).collect();")
    print("    t3_name(&name)")
    print("        .or_else(|| candidates.iter().find_map(|c| t3_extension(c)))")
    print("        .or_else(|| built_in_name(&name))")
    print("        .or_else(|| candidates.iter().find_map(|c| complete_override(c).or_else(|| built_in_extension(c))))")
    print(f"        .unwrap_or(&{default})")
    print("}")


if __name__ == "__main__":
    sys.exit(main())
