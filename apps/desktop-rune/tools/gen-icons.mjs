// Emit every lucide-react icon apps/web imports as a Rune `Icon` static. usage: node gen-icons.mjs <repo> > icons_lucide.rs
import { readFileSync, readdirSync, statSync, realpathSync } from "node:fs";
import { join, dirname } from "node:path";
const repo = process.argv[2];
const files = [];
const walk = (d) => { for (const n of readdirSync(d)) { const p = join(d, n); if (n === "node_modules") continue; const s = statSync(p); if (s.isDirectory()) walk(p); else if (/\.tsx?$/.test(n)) files.push(p); } };
for (const d of ["apps/web/src", "packages/client-runtime/src"]) walk(join(repo, d));
const used = new Set();
for (const f of files) {
  const src = readFileSync(f, "utf8");
  for (const m of src.matchAll(/import\s*(?:type\s*)?\{([^}]*)\}\s*from\s*"lucide-react"/g))
    for (const part of m[1].split(",")) { const name = part.trim().split(/\s+as\s+/)[0].trim(); if (name && name !== "type" && !name.startsWith("type ")) used.add(name); }
}
const pkg = dirname(realpathSync(join(repo, "apps/web/node_modules/lucide-react/package.json")));
const index = readFileSync(join(pkg, "dist/esm/lucide-react.js"), "utf8");
const fileOf = new Map();
for (const m of index.matchAll(/export \{([^}]*)\} from '\.\/icons\/([^']+)\.js'/g))
  for (const part of m[1].split(",")) { const alias = part.trim().split(/\s+as\s+/)[1]; if (alias) fileOf.set(alias.trim(), m[2]); }
const byFile = new Map();
const missing = [];
for (const name of [...used].sort()) { const f = fileOf.get(name); if (!f) { missing.push(name); continue; } if (!byFile.has(f)) byFile.set(f, name); }
const esc = (s) => s.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
let out = "//! Generated by gen-icons.mjs from lucide-react: every icon apps/web imports. Do not edit.\n#![allow(dead_code)]\n\nuse rune::Icon;\n\n";
for (const [f, name] of [...byFile].sort()) {
  const src = readFileSync(join(pkg, "dist/esm/icons", f + ".js"), "utf8");
  const node = src.match(/const __iconNode = (\[[\s\S]*?\]);\n/);
  const nodes = (0, eval)(node[1]);
  const body = nodes.map(([tag, attrs]) => "<" + tag + Object.entries(attrs).filter(([k]) => k !== "key").map(([k, v]) => ` ${k}="${v}"`).join("") + ' stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" fill="none"/>').join("");
  const id = f.toUpperCase().replace(/-/g, "_");
  out += `pub static ${id}: Icon = Icon { name: "${f}", view: 24.0, body: "${esc(body)}" };\n`;
}
process.stdout.write(out);
console.error(`${byFile.size} icons; unresolved: ${missing.join(" ")}`);
