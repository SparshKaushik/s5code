"""gen-tokens.py tokens.json > tokens.rs: the web app's resolved colour tokens as linear Rune colours."""
import json, math, re, sys
d = json.load(open(sys.argv[1]))
COLORISH = re.compile(r"^(oklch|oklab|rgb|rgba|#|color|hsl|black|white|transparent|var\(|light-dark)", re.I)
def lin(c): return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4
def oklab_to_linear(L, a, b):
    l_ = L + 0.3963377774 * a + 0.2158037573 * b
    m_ = L - 0.1055613458 * a - 0.0638541728 * b
    s_ = L - 0.0894841775 * a - 1.2914855480 * b
    l, m, s = l_ ** 3, m_ ** 3, s_ ** 3
    return (4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
            -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
            -0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s)
def num(x):
    x = x.strip()
    if x == "none": return 0.0
    if x.endswith("%"): return float(x[:-1]) / 100
    return float(x)
def parse(css):
    m = re.match(r"(\w+)\((.*)\)$", css.strip())
    fn, body = m.group(1), m.group(2)
    alpha = 1.0
    if "/" in body: body, a = body.split("/"); alpha = num(a)
    parts = body.replace(",", " ").split()
    if fn in ("rgb", "rgba"):
        if len(parts) == 4: alpha = num(parts[3])
        r, g, b = (lin(float(p) / 255) for p in parts[:3])
    elif fn == "color":
        assert parts[0] == "srgb", css
        r, g, b = (lin(min(max(num(p), 0), 1)) for p in parts[1:4])
    elif fn == "oklab":
        r, g, b = oklab_to_linear(num(parts[0]), num(parts[1]), num(parts[2]))
    elif fn == "oklch":
        L, C, H = num(parts[0]), num(parts[1]), num(parts[2])
        r, g, b = oklab_to_linear(L, C * math.cos(math.radians(H)), C * math.sin(math.radians(H)))
    else: raise ValueError(css)
    # Chrome clips out-of-gamut colours per channel in gamma space.
    clip = lambda v: lin(min(max((1.055 * v ** (1 / 2.4) - 0.055) if v > 0.0031308 else 12.92 * v, 0), 1)) if v > 0 else 0.0
    return tuple(round(clip(v), 6) for v in (r, g, b)) + (round(alpha, 4),)
def lit(c): return "Color { r: %r, g: %r, b: %r, a: %r }" % tuple(float(v) for v in c)
PAL = re.compile(r"^--color-(red|orange|amber|yellow|lime|green|emerald|teal|cyan|sky|blue|indigo|violet|purple|fuchsia|pink|rose|slate|gray|zinc|neutral|stone|mauve|olive|mist|taupe)-(\d+)$")
names = []
for n, v in d["dark"]["colors"].items():
    raw = d["dark"]["raw"].get(n, "")
    if PAL.match(n) or n.startswith("--color-") or n.startswith("--stage-") or n.startswith("--tw-"): continue
    if not COLORISH.match(raw) and not COLORISH.match(d["light"]["raw"].get(n, "")): continue
    if any(n not in d[k]["colors"] for k in ("light", "sidebar-dark", "sidebar-light")): continue
    names.append(n)
ident = lambda n: n[2:].replace("-", "_")
out = ["//! Generated by gen-tokens.py from the live web app's computed colours (apps/web/src/index.css).",
       "//! Do not edit; rerun the generator after a token change.", "#![allow(dead_code)]", "", "use rune::Color;", "",
       "#[derive(Clone, Copy, Debug)]", "pub struct Tokens {"]
out += [f"    pub {ident(n)}: Color," for n in names] + ["}", ""]
for scheme in ("dark", "light", "sidebar-dark", "sidebar-light"):
    if scheme.startswith("sidebar"): out.append("/// Inside `[data-app-sidebar]`, which re-points several tokens (index.css).")
    out.append(f"pub const {scheme.upper().replace('-', '_')}: Tokens = Tokens {{")
    for n in names: out.append(f"    {ident(n)}: {lit(parse(d[scheme]['colors'][n]['css']))}, // {d[scheme]['colors'][n]['css'][:60]}")
    out += ["};", ""]
out.append("/// Tailwind's palette, as `bg-emerald-500` and friends resolve it.")
out.append("pub mod tw {\n    use rune::Color;")
for n, v in d["dark"]["colors"].items():
    m = PAL.match(n)
    if m: out.append(f"    pub const {m.group(1).upper()}_{m.group(2)}: Color = {lit(parse(v['css']))};")
out.append("}")
print("\n".join(out))
